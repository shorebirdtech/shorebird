/// A reference to a [CodeSigner] instance.
final codeSignerRef = create(CodeSigner.new);

/// The [CodeSigner] instance available in the current zone.
CodeSigner get codeSigner => read(codeSignerRef);

/// The format of a PEM-encoded private key.
enum PrivateKeyFormat {
  /// PKCS#8 format with header "-----BEGIN PRIVATE KEY-----".
  /// Generated by: openssl genpkey -algorithm RSA
  pkcs8,

  /// PKCS#1 format with header "-----BEGIN RSA PRIVATE KEY-----".
  /// Generated by: openssl genrsa
  pkcs1,
}

/// {@template invalid_public_key_exception}
/// A public key option supplied something other than exactly one PEM public
/// key. [message] completes "The --public-key-path file ..." or "The
/// --public-key-cmd output ...", and never quotes what was supplied.
/// {@endtemplate}
class InvalidPublicKeyException extends FormatException {
  /// {@macro invalid_public_key_exception}
  const InvalidPublicKeyException(super.message);
}

/// The DER object identifier of `rsaEncryption`, which a
/// SubjectPublicKeyInfo names as its algorithm for an RSA key.
const _rsaEncryptionOid = '1.2.840.113549.1.1.1';

/// {@template code_signer}
/// Manages code signing operations.
/// {@endtemplate}
class CodeSigner {
  /// Signs a [message] using the provided [privateKeyPemFile] using
  /// SHA-256/RSA.
  ///
  /// This is the equivalent of:
  ///   $ openssl dgst -sha256 -sign privateKey.pem -out signature message
  ///
  /// Supports both PKCS#8 ("BEGIN PRIVATE KEY") and PKCS#1
  /// ("BEGIN RSA PRIVATE KEY") formats.
  String sign({required String message, required File privateKeyPemFile}) {
    final pemString = privateKeyPemFile.readAsStringSync();
    final (keyBytes, format) = _parsePrivateKeyPem(pemString);
    final privateKey = _RSAPrivateKeyFromBytes.from(keyBytes, format);

    final signer = Signer('SHA-256/RSA')
      ..init(true, PrivateKeyParameter<RSAPrivateKey>(privateKey));

    final signature =
        signer.generateSignature(utf8.encode(message)) as RSASignature;
    return base64.encode(signature.bytes);
  }

  /// Extracts the base64 encoded DER from a public key PEM file. The DER is
  /// simply the modulus and exponent of the public key, without information
  /// about the algorithm or or ASN1 object type identifier.
  String base64PublicKey(File publicKeyPemFile) {
    return base64PublicKeyFromPem(publicKeyPemFile.readAsStringSync());
  }

  /// Extracts the base64 encoded DER from a PEM-encoded public key string.
  String base64PublicKeyFromPem(String publicKeyPem) {
    final publicKey = _RSAPublicKeyFromBytes.rsaPublicKeyFromBytes(
      PemCodec(PemLabel.publicKey).decode(publicKeyPem),
    );

    final publicKeySeq = ASN1Sequence()
      ..add(ASN1Integer(publicKey.modulus))
      ..add(ASN1Integer(publicKey.exponent))
      ..encode();
    return base64.encode(publicKeySeq.encodedBytes!);
  }

  /// Returns the RSA public key in [pem], which must be exactly one PEM
  /// public key (`BEGIN PUBLIC KEY`) and nothing else, re-encoded from the
  /// parsed key rather than copied.
  ///
  /// The CLI embeds and sends only what this returns, so no byte of [pem]
  /// beyond the key itself reaches a release or Shorebird, even if other
  /// data was hidden inside the block. A private key is refused outright, in
  /// any PEM form, so a swapped `--public-key-path` and `--private-key-path`
  /// cannot put the private key in an app or send it to Shorebird. Throws an
  /// [InvalidPublicKeyException] whose message never quotes [pem], since
  /// [pem] may be a private key.
  String canonicalPublicKeyPem(String pem) {
    if (pem.contains('PRIVATE KEY')) {
      throw const InvalidPublicKeyException(
        'contains a private key. Never pass a private key here: pass the '
        'public key, which `openssl rsa -in private.pem -pubout -out '
        'public.pem` writes, and give the private key only to '
        '--private-key-path.',
      );
    }
    const notOneKey = InvalidPublicKeyException(
      'must contain exactly one PEM public key (BEGIN PUBLIC KEY) and '
      'nothing else.',
    );
    final trimmed = pem.trim();
    if (RegExp('-----BEGIN ').allMatches(pem).length != 1 ||
        RegExp('-----END ').allMatches(pem).length != 1 ||
        !trimmed.startsWith('-----BEGIN PUBLIC KEY-----') ||
        !trimmed.endsWith('-----END PUBLIC KEY-----')) {
      throw notOneKey;
    }
    final RSAPublicKey key;
    try {
      final der = PemCodec(PemLabel.publicKey).decode(trimmed);
      final parser = ASN1Parser(Uint8List.fromList(der));
      final info = parser.nextObject() as ASN1Sequence;
      // Bytes after the key would be copied nowhere, but are refused so the
      // block holds nothing but the key.
      if (parser.hasNext()) throw notOneKey;
      final algorithm = info.elements![0] as ASN1Sequence;
      final oid = algorithm.elements![0] as ASN1ObjectIdentifier;
      if (oid.objectIdentifierAsString != _rsaEncryptionOid) {
        throw const InvalidPublicKeyException(
          'is not an RSA public key. Patch signing uses RSA keys.',
        );
      }
      key = _RSAPublicKeyFromBytes.rsaPublicKeyFromBytes(der);
    } on InvalidPublicKeyException {
      rethrow;
      // Malformed DER fails in ASN.1 parsing with errors and exceptions
      // that can carry the input, so whatever is thrown is replaced.
      // ignore: avoid_catches_without_on_clauses
    } catch (_) {
      throw const InvalidPublicKeyException('is not a valid public key.');
    }
    final publicKey = ASN1Sequence()
      ..add(ASN1Integer(key.modulus))
      ..add(ASN1Integer(key.exponent))
      ..encode();
    final info = ASN1Sequence()
      ..add(
        ASN1Sequence()
          ..add(ASN1ObjectIdentifier.fromIdentifierString(_rsaEncryptionOid))
          ..add(ASN1Null())
          ..encode(),
      )
      ..add(ASN1BitString(stringValues: publicKey.encodedBytes))
      ..encode();
    return PemCodec(PemLabel.publicKey).encode(info.encodedBytes!);
  }

  /// Runs a command and returns its stdout, expected to be a PEM public key.
  Future<String> runPublicKeyCmd(String command) async {
    final result = await process.run(
      'sh',
      ['-c', command],
    );

    if (result.exitCode != 0) {
      throw ProcessException(
        command,
        [],
        'Command failed with exit code ${result.exitCode}: ${result.stderr}',
        result.exitCode,
      );
    }

    final output = '${result.stdout}'.trim();
    // The output is never quoted in an error: a command that prints the
    // wrong thing may print a private key, in PEM or in a form no check
    // recognizes, and an error lands in the terminal and in CI logs.
    if (output.isEmpty) {
      throw const InvalidPublicKeyException(
        'is empty. The command must print a PEM-encoded public key.',
      );
    }
    return output;
  }

  /// Signs data by piping it to a command's stdin and reading the base64
  /// signature from stdout.
  Future<String> signWithCmd({
    required String data,
    required String command,
  }) async {
    final proc = await process.start(
      'sh',
      ['-c', command],
    );

    // Write data to stdin and close it
    proc.stdin.write(data);
    await proc.stdin.close();

    // Read stdout and stderr concurrently to avoid potential deadlock
    final results = await Future.wait([
      proc.stdout.transform(utf8.decoder).join(),
      proc.stderr.transform(utf8.decoder).join(),
    ]);
    final stdout = results[0];
    final stderr = results[1];
    final exitCode = await proc.exitCode;

    if (exitCode != 0) {
      throw ProcessException(
        command,
        [],
        'Sign command failed with exit code $exitCode: $stderr',
        exitCode,
      );
    }

    final signature = stdout.trim();
    if (signature.isEmpty) {
      throw const FormatException('Sign command produced no output');
    }

    return signature;
  }

  /// Verifies a signature against a message using a PEM-encoded public key.
  bool verify({
    required String message,
    required String signature,
    required String publicKeyPem,
  }) {
    final publicKey = _RSAPublicKeyFromBytes.rsaPublicKeyFromBytes(
      PemCodec(PemLabel.publicKey).decode(publicKeyPem),
    );

    final signer = Signer('SHA-256/RSA')
      ..init(false, PublicKeyParameter<RSAPublicKey>(publicKey));

    try {
      return signer.verifySignature(
        utf8.encode(message),
        RSASignature(base64.decode(signature)),
      );
    } on Exception {
      return false;
    }
  }

  /// Parses a PEM-encoded private key string and returns the key bytes along
  /// with the detected format.
  ///
  /// Supports both PKCS#8 and PKCS#1 formats.
  (List<int>, PrivateKeyFormat) _parsePrivateKeyPem(String pemString) {
    // Try PKCS#8 format first (BEGIN PRIVATE KEY) - natively supported.
    final pkcs8Blocks = decodePemBlocks(PemLabel.privateKey, pemString);
    if (pkcs8Blocks.isNotEmpty) {
      return (pkcs8Blocks.first, PrivateKeyFormat.pkcs8);
    }

    // Try PKCS#1 format (BEGIN RSA PRIVATE KEY).
    // The pem package only supports RFC 7468 labels and doesn't include
    // "RSA PRIVATE KEY", so we validate the label ourselves and use
    // unsafeIgnoreLabel for parsing.
    // See: https://github.com/google/dart-neats/issues/198
    if (pemString.contains('-----BEGIN RSA PRIVATE KEY-----')) {
      final blocks = decodePemBlocks(
        PemLabel.privateKey,
        pemString,
        unsafeIgnoreLabel: true,
      );
      if (blocks.isNotEmpty) {
        return (blocks.first, PrivateKeyFormat.pkcs1);
      }
    }

    throw const FormatException(
      'No valid PEM private key found. Expected "BEGIN PRIVATE KEY" (PKCS#8) '
      'or "BEGIN RSA PRIVATE KEY" (PKCS#1) format.',
    );
  }
}

extension _RSAPrivateKeyFromBytes on RSAPrivateKey {
  /// Converts RSA private key bytes to a pointycastle [RSAPrivateKey].
  ///
  /// Supports both PKCS#8 and PKCS#1 formats based on the [format] parameter.
  ///
  /// Based on https://github.com/konstantinullrich/crypton/blob/trunk/lib/src/rsa/private_key.dart
  static RSAPrivateKey from(
    List<int> privateKeyBytes,
    PrivateKeyFormat format,
  ) {
    final asn1Parser = ASN1Parser(Uint8List.fromList(privateKeyBytes));
    final topLevelSeq = asn1Parser.nextObject() as ASN1Sequence;

    final ASN1Sequence pkSeq;
    switch (format) {
      case PrivateKeyFormat.pkcs8:
        // PKCS#8: The RSA key is wrapped in an envelope, extract from
        // element[2].
        final privateKeyOctet = topLevelSeq.elements![2];
        final innerParser = ASN1Parser(privateKeyOctet.valueBytes);
        pkSeq = innerParser.nextObject() as ASN1Sequence;
      case PrivateKeyFormat.pkcs1:
        // PKCS#1: The RSA key is directly at the top level
        pkSeq = topLevelSeq;
    }

    // RSAPrivateKey structure (same for both formats at this point):
    // version, modulus, publicExponent, privateExponent, prime1, prime2, ...
    final modulus = pkSeq.elements![1] as ASN1Integer;
    final privateExponent = pkSeq.elements![3] as ASN1Integer;
    final p = pkSeq.elements![4] as ASN1Integer;
    final q = pkSeq.elements![5] as ASN1Integer;

    return RSAPrivateKey(
      modulus.integer!,
      privateExponent.integer!,
      p.integer,
      q.integer,
    );
  }
}

extension _RSAPublicKeyFromBytes on RSAPublicKey {
  /// Converts an RSA public key to a pointycastle [RSAPublicKey].
  ///
  /// Based on https://github.com/Ephenodrom/Dart-Basic-Utils/blob/45ed0a3087b2051004f17b39eb5289874b9c0390/lib/src/CryptoUtils.dart#L525-L547
  static RSAPublicKey rsaPublicKeyFromBytes(List<int> bytes) {
    final asn1Parser = ASN1Parser(Uint8List.fromList(bytes));
    final topLevelSeq = asn1Parser.nextObject() as ASN1Sequence;
    final publicKeyBitString = topLevelSeq.elements![1] as ASN1BitString;
    final publicKeyAsn = ASN1Parser(
      publicKeyBitString.stringValues as Uint8List?,
    );
    final publicKeySeq = publicKeyAsn.nextObject() as ASN1Sequence;
    final modulus = publicKeySeq.elements![0] as ASN1Integer;
    final exponent = publicKeySeq.elements![1] as ASN1Integer;

    return RSAPublicKey(modulus.integer!, exponent.integer!);
  }
}
